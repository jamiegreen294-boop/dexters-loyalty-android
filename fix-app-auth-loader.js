const fs=require('fs');
const zlib=require('zlib');
const path=require('path');
const file=path.join(__dirname,'dist','app-auth.js');
if(!fs.existsSync(file)) throw new Error('dist/app-auth.js not found');
const src=fs.readFileSync(file,'utf8');
if(!src.includes('DecompressionStream')) process.exit(0);
const m=src.match(/const b='([A-Za-z0-9+/=]+)'/);
if(!m) throw new Error('Could not locate compressed app payload');
const code=zlib.gunzipSync(Buffer.from(m[1],'base64')).toString('utf8');
if(!code.includes('supabase')||code.length<1000) throw new Error('Decoded app-auth payload failed validation');
fs.writeFileSync(file,code+'\n');
console.log('Replaced compressed app-auth loader with direct JavaScript startup.');
